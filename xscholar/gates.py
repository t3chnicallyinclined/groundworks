# -*- coding: utf-8 -*-
"""gates.py -- generate the datastore schema, the promotion gates, and a probe pair per gate.

From the instance config alone:
  schema_surql(inst)   tables and fields, with enumerated values enforced
  gate_surql(inst)     one ASSERT per gate rule, expanded from the config, holding on raw writes
  probes(inst)         for EVERY rule: a write that must be refused, then the same write accepted
  run_probes(inst, db) run them, clean up even on failure, report both counts

    python engine/gates.py INSTANCE.yaml --emit schema|gates|probes
    python engine/gates.py INSTANCE.yaml --apply --url http://127.0.0.1:8021/sql --ns demo --db incident

A gate with only one probe is a bug: a rule that only rejects, or only accepts, is broken.
Standard library only.
"""
import argparse
import json
import pathlib
import sys

import pathlib as _pathlib, sys as _sys
if __package__ in (None, ""):  # run as a plain script: make the repo root importable
    _sys.path.insert(0, str(next(d for d in _pathlib.Path(__file__).resolve().parents if (d / "pyproject.toml").exists())))
from xscholar import config  # noqa: E402

# Edge tables the engine knows, as (source table, target table). An instance's gate rules name
# edges; the direction of the traversal in the ASSERT comes from this map.
EDGES = {
    "cites": ("fact", "unit"),
    "supports": ("fact", "conclusion"),
    "undercuts": ("fact", "conclusion"),
    "attacks": ("critique", "conclusion"),
    "answers": ("answer", "critique"),
    "bears_on": ("label", "conclusion"),   # a label bears on a target; targets are conclusion rows
    "relies_on": ("conclusion", "authority"),
}

FACT_STATUSES = ["proposed", "inferred", "open", "confirmed", "ruled_out", "stale", "superseded"]
CRITIQUE_VERDICTS = ["fatal", "damaging", "survivable"]


class GateError(Exception):
    pass


def _lit(values):
    return "[" + ", ".join("'%s'" % str(v).replace("'", "\\'") for v in values) + "]"


# ---- schema --------------------------------------------------------------------------------------

def schema_surql(inst):
    v = inst.allowed_vocabulary()
    lines = [
        "-- generated by engine/gates.py from instance %s; do not edit by hand" % inst.id,
        "DEFINE TABLE OVERWRITE unit SCHEMAFULL;",
        "DEFINE FIELD OVERWRITE type ON unit TYPE string ASSERT $value IN %s;" % _lit(inst.unit_names()),
        "DEFINE FIELD OVERWRITE text ON unit TYPE string;",
        "DEFINE FIELD OVERWRITE locator ON unit TYPE object FLEXIBLE;",
        "DEFINE FIELD OVERWRITE status ON unit TYPE string ASSERT $value IN %s;" % _lit(inst.status_values()),
        "DEFINE FIELD OVERWRITE grade ON unit TYPE string ASSERT $value IN %s;" % _lit(inst.grades()),
        "DEFINE FIELD OVERWRITE hash ON unit TYPE string;",
        "DEFINE FIELD OVERWRITE meta ON unit TYPE option<object> FLEXIBLE;",
        "DEFINE INDEX OVERWRITE unit_type_status ON unit FIELDS type, status;",
        "",
        "DEFINE TABLE OVERWRITE label SCHEMAFULL;",
        "DEFINE FIELD OVERWRITE unit ON label TYPE record<unit>;",
        "DEFINE FIELD OVERWRITE tier ON label TYPE int ASSERT $value IN %s;" % json.dumps(list(v["tiers"])),
        "DEFINE FIELD OVERWRITE dir ON label TYPE option<string> ASSERT $value = NONE OR $value IN %s;" % _lit(v["directions"]),
        "DEFINE FIELD OVERWRITE issues ON label TYPE array<string> ASSERT array::all($value, |$i| $i IN %s);" % _lit(v["issues"]),
        "DEFINE FIELD OVERWRITE targets ON label TYPE array<string>;",
        "DEFINE FIELD OVERWRITE role ON label TYPE option<string> ASSERT $value = NONE OR $value IN %s;" % _lit(v["roles"]),
        "DEFINE FIELD OVERWRITE reason ON label TYPE option<string>;",
        "DEFINE FIELD OVERWRITE quote ON label TYPE option<string>;",
        "DEFINE FIELD OVERWRITE grade ON label TYPE string DEFAULT 'agent' ASSERT $value = 'agent';",
        "DEFINE FIELD OVERWRITE chunk ON label TYPE string;",
        "DEFINE FIELD OVERWRITE run ON label TYPE string;",
        "",
        "DEFINE TABLE OVERWRITE fact SCHEMAFULL;",
        "DEFINE FIELD OVERWRITE statement ON fact TYPE string;",
        "DEFINE FIELD OVERWRITE status ON fact TYPE string DEFAULT 'proposed';",
        "DEFINE FIELD OVERWRITE note ON fact TYPE option<string>;",
        "DEFINE FIELD OVERWRITE tried ON fact TYPE option<string>;",
        "DEFINE FIELD OVERWRITE evidence ON fact TYPE option<string>;",
        "DEFINE FIELD OVERWRITE reasoning_type ON fact TYPE option<string>;",
        "DEFINE FIELD OVERWRITE author ON fact TYPE option<string>;",
        "DEFINE FIELD OVERWRITE lens ON fact TYPE option<string>;",
        "DEFINE FIELD OVERWRITE learned_at ON fact TYPE datetime DEFAULT time::now();",
        "",
        "DEFINE TABLE OVERWRITE conclusion SCHEMAFULL;",
        "DEFINE FIELD OVERWRITE statement ON conclusion TYPE string;",
        "DEFINE FIELD OVERWRITE ready ON conclusion TYPE bool DEFAULT false;",
        "DEFINE FIELD OVERWRITE rating ON conclusion TYPE option<string>;",
        "DEFINE FIELD OVERWRITE author ON conclusion TYPE option<string>;",
        "",
        "DEFINE TABLE OVERWRITE authority SCHEMAFULL;",
        "DEFINE FIELD OVERWRITE citation ON authority TYPE string;",
        "DEFINE FIELD OVERWRITE verified ON authority TYPE bool DEFAULT false;",
        "DEFINE FIELD OVERWRITE source_grade ON authority TYPE option<string>;",
        "",
        "DEFINE TABLE OVERWRITE critique SCHEMAFULL;",
        "DEFINE FIELD OVERWRITE lens ON critique TYPE string;",
        "DEFINE FIELD OVERWRITE head ON critique TYPE string;",
        "DEFINE FIELD OVERWRITE verdict ON critique TYPE string ASSERT $value IN %s;" % _lit(CRITIQUE_VERDICTS),
        "DEFINE FIELD OVERWRITE text ON critique TYPE option<string>;",
        "DEFINE FIELD OVERWRITE author ON critique TYPE option<string>;",
        "DEFINE FIELD OVERWRITE answered ON critique TYPE bool DEFAULT false;",
        "",
        "DEFINE TABLE OVERWRITE answer SCHEMAFULL;",
        "DEFINE FIELD OVERWRITE text ON answer TYPE string;",
        "DEFINE FIELD OVERWRITE author ON answer TYPE option<string>;",
        "",
    ]
    for edge, (src, dst) in EDGES.items():
        lines.append("DEFINE TABLE OVERWRITE %s TYPE RELATION IN %s OUT %s SCHEMALESS;" % (edge, src, dst))
    return "\n".join(lines) + "\n"


# ---- gates -----------------------------------------------------------------------------------------

def _expand(where, inst):
    return (where or "").replace("$confirming", _lit(inst.confirming_grades())) \
                        .replace("$usable", _lit(inst.usable_statuses()))


def _traversal(rule_table, clause, inst):
    """The subquery counting matching neighbours of $this for one requires/forbids clause."""
    edge = clause.get("edge")
    if edge not in EDGES:
        raise GateError("gate %s: unknown edge %r; known: %s" % (rule_table, edge, ", ".join(EDGES)))
    src, dst = EDGES[edge]
    if rule_table == src:
        path, other = "->%s->%s" % (edge, dst), dst
    elif rule_table == dst:
        path, other = "<-%s<-%s" % (edge, src), src
    else:
        raise GateError("edge %s joins %s and %s; it does not touch table %s" % (edge, src, dst, rule_table))
    declared = clause.get("to") or clause.get("from")
    if declared and other not in declared:
        raise GateError("edge %s from %s reaches %s, not %s" % (edge, rule_table, other, declared))
    where = _expand(clause.get("where"), inst)
    return "count(SELECT VALUE id FROM $this%s%s)" % (path, " WHERE " + where if where else "")


def gate_expression(rule, inst):
    """The boolean that must hold when rule.field takes rule.value."""
    parts = []
    for clause in rule.get("requires") or []:
        parts.append("%s >= %d" % (_traversal(rule["table"], clause, inst), int(clause.get("min", 1))))
    for clause in rule.get("forbids") or []:
        parts.append("%s = 0" % _traversal(rule["table"], clause, inst))
    if not parts:
        raise GateError("gate %s requires or forbids nothing" % rule["id"])
    return " AND ".join(parts)


def _value_literal(value):
    if isinstance(value, bool):
        return "true" if value else "false"
    if isinstance(value, (int, float)):
        return str(value)
    return "'%s'" % str(value).replace("'", "\\'")


def gate_surql(inst):
    """One ASSERT per rule. Rules on the same field are combined into one field definition."""
    by_field = {}
    for rule in inst.gate_rules():
        by_field.setdefault((rule["table"], rule["field"]), []).append(rule)
    lines = ["-- generated by engine/gates.py from instance %s; human-owned rules, do not edit by hand" % inst.id]
    for (table, field), rules in by_field.items():
        conditions = []
        for rule in rules:
            conditions.append("($value != %s OR (%s))" % (_value_literal(rule["value"]), gate_expression(rule, inst)))
        if table == "fact" and field == "status":
            typ, enum = "string", " AND $value IN %s" % _lit(FACT_STATUSES)
            default = " DEFAULT 'proposed'"
        elif field in ("ready", "verified"):
            typ, enum, default = "bool", "", " DEFAULT false"
        else:
            typ, enum, default = "string", "", ""
        lines.append("DEFINE FIELD OVERWRITE %s ON %s TYPE %s%s ASSERT %s%s;  -- %s"
                     % (field, table, typ, default, " AND ".join(conditions), enum,
                        ", ".join(r["id"] for r in rules)))
    return "\n".join(lines) + "\n"


# ---- probes --------------------------------------------------------------------------------------

def _probe_ids(rule):
    base = "zz_probe_%s" % rule["id"]
    return {"row": "%s:%s" % (rule["table"], base), "ok": "unit:%s_ok" % base, "bad": "unit:%s_bad" % base,
            "fact": "fact:%s_f" % base, "crit": "critique:%s_c" % base, "auth": "authority:%s_a" % base}


def probes(inst):
    """For every rule: setup, a write that must be REFUSED, the fix, the same write ACCEPTED, cleanup."""
    out = []
    good_grade = inst.confirming_grades()[0]
    bad_grade = next(g for g in inst.grades() if g not in inst.confirming_grades())
    usable = inst.usable_statuses()[0]
    unusable = next(s for s in inst.status_values() if s not in inst.usable_statuses())
    unit_type = inst.unit_names()[0]
    for rule in inst.gate_rules():
        ids = _probe_ids(rule)
        table, field, value = rule["table"], rule["field"], _value_literal(rule["value"])
        setup, fix, cleanup = [], [], []
        # rows the rule's row will point at, or be pointed at by
        setup.append("CREATE %s SET type='%s', text='probe', locator={p: 1}, status='%s', grade='%s', hash='h';"
                     % (ids["ok"], unit_type, usable, good_grade))
        setup.append("CREATE %s SET type='%s', text='probe', locator={p: 2}, status='%s', grade='%s', hash='h';"
                     % (ids["bad"], unit_type, unusable, bad_grade))
        setup.append("CREATE %s SET statement='probe support fact', status='proposed';" % ids["fact"])
        if table == "fact":
            setup.append("CREATE %s SET statement='probe row', status='proposed';" % ids["row"])
        elif table == "conclusion":
            setup.append("CREATE %s SET statement='probe row', ready=false;" % ids["row"])
        elif table == "authority":
            setup.append("CREATE %s SET citation='probe', verified=false;" % ids["row"])
        else:
            raise GateError("no probe template for table %s" % table)
        attempt = "UPDATE %s SET %s = %s;" % (ids["row"], field, value)
        # the fix: satisfy every requires clause, and make sure no forbids clause matches
        for clause in rule.get("requires") or []:
            edge = clause["edge"]
            src, dst = EDGES[edge]
            n = int(clause.get("min", 1))
            for k in range(n):
                if table == src:
                    target = ids["ok"] if dst == "unit" else ids["fact"] if dst == "fact" else ids["auth"]
                    if dst == "authority":
                        setup.append("CREATE %s SET citation='probe authority', verified=false;" % ids["auth"])
                    fix.append("RELATE %s->%s->%s;" % (ids["row"], edge, target))
                else:
                    if src == "fact":
                        fix.append("RELATE %s->%s->%s;" % (ids["fact"], edge, ids["row"]))
                    elif src == "critique":
                        fix.append("CREATE %s SET lens='probe', head='probe head', verdict='survivable', answered=true;" % ids["crit"])
                        fix.append("RELATE %s->%s->%s;" % (ids["crit"], edge, ids["row"]))
                    elif src == "label":
                        raise GateError("gate %s: labels never gate promotion" % rule["id"])
        # a second, sharper refusal for citation rules: the wrong grade or status must not count
        wrong = []
        for clause in rule.get("requires") or []:
            if clause["edge"] == "cites" and clause.get("where"):
                wrong.append("RELATE %s->cites->%s;" % (ids["row"], ids["bad"]))
        for tab in ("critique", "answer"):
            cleanup.append("DELETE %s WHERE record::id(id) CONTAINS 'zz_probe_%s';" % (tab, rule["id"]))
        for tab in ("conclusion", "fact", "authority", "unit"):
            cleanup.append("DELETE %s WHERE record::id(id) CONTAINS 'zz_probe_%s';" % (tab, rule["id"]))
        out.append({"rule": rule["id"], "setup": setup, "attempt": attempt, "wrong": wrong, "fix": fix,
                    "cleanup": cleanup})
    return out


def run_probes(inst, db):
    """Run every probe pair. Return a report; never leave probe rows behind."""
    report = {"instance": inst.id, "rules": [], "rejected_ok": 0, "accepted_ok": 0, "misbehaved": 0}
    for probe in probes(inst):
        entry = {"rule": probe["rule"], "reject": None, "wrong_evidence_reject": None, "accept": None}
        try:
            for stmt in probe["setup"]:
                db.sql(stmt)
            ok, _ = db.try_sql(probe["attempt"])
            entry["reject"] = not ok
            if probe["wrong"]:
                for stmt in probe["wrong"]:
                    db.sql(stmt)
                ok, _ = db.try_sql(probe["attempt"])
                entry["wrong_evidence_reject"] = not ok
            for stmt in probe["fix"]:
                db.sql(stmt)
            ok, message = db.try_sql(probe["attempt"])
            entry["accept"] = ok
            entry["accept_error"] = "" if ok else message
        finally:
            for stmt in probe["cleanup"]:
                db.try_sql(stmt)
        behaved = entry["reject"] and entry["accept"] and entry["wrong_evidence_reject"] in (None, True)
        entry["behaved"] = bool(behaved)
        report["rejected_ok"] += 1 if entry["reject"] else 0
        report["accepted_ok"] += 1 if entry["accept"] else 0
        report["misbehaved"] += 0 if behaved else 1
        report["rules"].append(entry)
    return report


# ---- command line --------------------------------------------------------------------------------

def main(argv=None):
    parser = argparse.ArgumentParser(description="Generate schema, gates and probes from an instance config.")
    parser.add_argument("instance")
    parser.add_argument("--emit", choices=["schema", "gates", "probes"])
    parser.add_argument("--apply", action="store_true", help="apply schema and gates, then run the probes")
    parser.add_argument("--url", default="http://127.0.0.1:8002/sql")
    parser.add_argument("--ns")
    parser.add_argument("--db")
    args = parser.parse_args(argv)
    inst = config.load(args.instance)
    if args.emit == "schema":
        print(schema_surql(inst)); return 0
    if args.emit == "gates":
        print(gate_surql(inst)); return 0
    if args.emit == "probes":
        print(json.dumps(probes(inst), indent=2)); return 0
    if args.apply:
        from xscholar import db as dbmod
        conn = dbmod.Db(url=args.url, ns=args.ns or inst.id, db=args.db or inst.id)
        conn.ping()
        conn.script(schema_surql(inst))
        conn.script(gate_surql(inst))
        report = run_probes(inst, conn)
        print(json.dumps(report, indent=2))
        print("PROBES: %d rejected as required, %d accepted as required, %d misbehaved"
              % (report["rejected_ok"], report["accepted_ok"], report["misbehaved"]))
        return 1 if report["misbehaved"] else 0
    parser.error("choose --emit or --apply")


if __name__ == "__main__":
    sys.exit(main())
