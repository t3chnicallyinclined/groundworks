# Tables the queue watches. `unit` is included because the stale re-check reacts to a unit's grade or
# status changing; `cites` because a lost citation is the other way a confirmed fact goes stale.
TABLES = ("unit", "fact", "conclusion", "critique", "cites")
# Tables whose last-seen row image the worker keeps so a delete can still be archived or traced.
IMAGE_CACHE_TABLES = ("fact", "conclusion", "critique", "cites")
KINDS = ("create", "update", "delete")


class QueueError(Exception):
    pass


class PatchError(QueueError):
    """The reverse patch in a feed entry could not be applied to the after-image."""


# ---- surql ---------------------------------------------------------------------------------------

def changefeed_surql(inst, retention="7d", tables=TABLES):
    """CHANGEFEED on each watched table, plus the `review` and `archive` tables the handlers write.

    Uses ALTER TABLE, not DEFINE TABLE OVERWRITE: on 3.1.6 a bare `DEFINE TABLE OVERWRITE fact
    CHANGEFEED 7d` keeps the fields but silently turns the table SCHEMALESS, and a later
    `DEFINE TABLE OVERWRITE fact SCHEMAFULL` (what schema_surql emits) silently drops the changefeed.
    Apply this AFTER the schema and gates, and again after every schema re-apply.
    """
    lines = ["-- generated by xscholar/queue.py from instance %s; apply after schema and gates" % inst.id]
    for table in tables:
        lines.append("ALTER TABLE %s CHANGEFEED %s INCLUDE ORIGINAL;" % (table, retention))
    lines += [
        "",
        "-- work-queue outputs; field names follow xscholar/patterns/archive_bin.surql and tms_propagation.surql",
        "DEFINE TABLE IF NOT EXISTS review SCHEMALESS;",
        "DEFINE TABLE IF NOT EXISTS archive SCHEMALESS;",
    ]
    return "\n".join(lines) + "\n"


# ---- feed parsing --------------------------------------------------------------------------------

class Change(object):
    """One row change. `before` is None for a create, or when no image could be reconstructed."""
    __slots__ = ("table", "kind", "id", "before", "after", "changed_paths", "versionstamp", "raw", "before_error")

    def __init__(self, table, kind, id, before, after, changed_paths, versionstamp, raw, before_error=""):
        self.table, self.kind, self.id = table, kind, id
        self.before, self.after = before, after
        self.changed_paths = changed_paths
        self.versionstamp, self.raw, self.before_error = versionstamp, raw, before_error

    def changed(self, *fields):
        """True if any of these top-level fields differs between before and after."""
        return any(("/" + f) in self.changed_paths or any(p.startswith("/" + f + "/") for p in self.changed_paths)
                   for f in fields)

    def __repr__(self):
        return "Change(%s %s %s @%d)" % (self.kind, self.table, self.id, self.versionstamp)


def _unquote(segment):
    return urllib.parse.unquote(segment, errors="strict")


def apply_dmp_patch(text, patch_text):
    """Apply a diff-match-patch text patch (as SurrealDB emits in a `change` op) to `text`.

    The `-` side of every hunk is the current text; the result is the original. Lines are
    percent-encoded by the server for newline, %, non-ASCII and <>"; spaces and +/- are literal.
    """
    hunks, current = [], None
    for line in patch_text.split("\n"):
        if not line:
            continue
        if line.startswith("@@"):
            head = line[2:line.rindex("@@")].strip().split()
            if len(head) != 2 or not head[0].startswith("-") or not head[1].startswith("+"):
                raise PatchError("bad hunk header %r" % line)
            src = head[0][1:].split(",")
            start, length = int(src[0]), (int(src[1]) if len(src) > 1 else 1)
            current = {"start": start if length == 0 else start - 1, "lines": []}
            hunks.append(current)
        elif current is None or line[0] not in " -+":
            raise PatchError("bad patch line %r" % line)
        else:
            current["lines"].append((line[0], _unquote(line[1:])))
    out, pos = [], 0
    for hunk in hunks:
        if hunk["start"] < pos or hunk["start"] > len(text):
            raise PatchError("hunk start %d out of range (pos %d, len %d)" % (hunk["start"], pos, len(text)))
        out.append(text[pos:hunk["start"]])
        pos = hunk["start"]
        for kind, segment in hunk["lines"]:
            if kind in " -":
                if text[pos:pos + len(segment)] != segment:
                    raise PatchError("patch context %r does not match text at %d" % (segment[:40], pos))
                pos += len(segment)
            if kind in " +":
                out.append(segment)
    out.append(text[pos:])
    return "".join(out)


def _pointer(path):
    if not path.startswith("/"):
        raise PatchError("bad JSON pointer %r" % path)
    return [p.replace("~1", "/").replace("~0", "~") for p in path[1:].split("/")]


def _walk(container, parts):
    for part in parts:
        container = container[int(part)] if isinstance(container, list) else container[part]
    return container


def reverse_patch(after, ops):
    """Apply the reverse JSON patch from a feed entry to the after-image; return the before-image."""
    before = json.loads(json.dumps(after))
    for op in ops:
        parts = _pointer(op["path"])
        parent, key = _walk(before, parts[:-1]), parts[-1]
        if isinstance(parent, list):
            key = int(key)
        name = op.get("op")
        if name == "change":
            if not isinstance(parent[key], str):
                raise PatchError("change op on non-string at %s" % op["path"])
            parent[key] = apply_dmp_patch(parent[key], op["value"])
        elif name in ("replace", "add"):
            if isinstance(parent, list) and name == "add":
                parent.insert(key, op.get("value"))
            else:
                parent[key] = op.get("value")
        elif name == "remove":
            del parent[key]
        else:
            raise PatchError("unknown patch op %r" % name)
    return before


def parse_entry(table, entry, images=None):
    """Turn one SHOW CHANGES entry into Change objects. Schema entries yield nothing."""
    out, stamp = [], int(entry["versionstamp"])
    images = images if images is not None else {}
    for raw in entry.get("changes") or []:
        if "current" in raw:
            after = raw["current"]
            ops = raw.get("update") or []
            paths = sorted({op.get("path") for op in ops if isinstance(op, dict) and op.get("path")})
            try:
                before, error = reverse_patch(after, ops), ""
            except (PatchError, KeyError, IndexError, TypeError, ValueError) as exc:
                before, error = None, "before-image not reconstructed: %s" % exc
            out.append(Change(table, "update", str(after.get("id")), before, after, paths, stamp, raw, error))
        elif isinstance(raw.get("update"), dict):
            after = raw["update"]
            out.append(Change(table, "create", str(after.get("id")), None, after, ["/"], stamp, raw))
        elif "delete" in raw:
            rid = str(raw["delete"].get("id"))
            before = images.get(rid)
            error = "" if before is not None else "no before-image: server gives none for deletes and the row was not in the worker's image cache"
            out.append(Change(table, "delete", rid, before, None, ["/"], stamp, raw, error))
        # define_table and anything else: schema noise, skipped
    return out


# ---- the worker ----------------------------------------------------------------------------------

def _load_state(path):
    path = pathlib.Path(path)
    if not path.exists():
        return {"versionstamps": {}, "images": {}}
    try:
        state = json.loads(path.read_text(encoding="utf-8"))
    except ValueError as exc:
        raise QueueError("state file %s is not JSON (%s); refusing to guess a versionstamp" % (path, exc))
    state.setdefault("versionstamps", {})
    state.setdefault("images", {})
    return state


def _save_state(path, state):
    path = pathlib.Path(path)
    path.parent.mkdir(parents=True, exist_ok=True)
    tmp = path.with_name(path.name + ".tmp")
    tmp.write_text(json.dumps(state, sort_keys=True), encoding="utf-8")
    os.replace(str(tmp), str(path))


class Worker(object):
    """Reads each watched table's feed since its stored versionstamp and dispatches to handlers.

    handlers: {(table, kind): callable or [callables]}; each is called as handler(change, db).
    """

    def __init__(self, db, state_path, handlers, tables=TABLES, batch=200, replay_from_start=False,
                 image_cache_tables=IMAGE_CACHE_TABLES):
        self.db = db
        self.state_path = str(state_path)
        self.handlers = {}
        for key, value in (handlers or {}).items():
            if key[1] not in KINDS:
                raise QueueError("handler key %r: kind must be one of %s" % (key, ", ".join(KINDS)))
            self.handlers[key] = list(value) if isinstance(value, (list, tuple)) else [value]
        self.tables = tuple(tables)
        self.batch = int(batch)
        self.replay_from_start = bool(replay_from_start)
        self.image_cache_tables = tuple(image_cache_tables)
        self.state = _load_state(self.state_path)
        # Test-only knob that BREAKS the delivery guarantee: advance the versionstamp before dispatch.
        # tests/test_queue.py flips it to prove the guarantee is load-bearing. Never set it in service.
        self._advance_before_dispatch = False

    # -- feed access --

    def show(self, table, since, limit):
        stmt = "SHOW CHANGES FOR TABLE %s SINCE %d LIMIT %d" % (table, int(since), int(limit))
        return self.db.sql(stmt, expect=1)[0] or []

    def feed_end(self, table):
        """The last versionstamp currently in the table's feed (0 if empty). Pages the whole feed."""
        last = 0
        while True:
            page = self.show(table, last + 1, self.batch)
            if not page:
                return last
            last = int(page[-1]["versionstamp"])
            if len(page) < self.batch:
                return last

    def versionstamp(self, table):
        return self.state["versionstamps"].get(table)

    def _set_versionstamp(self, table, stamp):
        self.state["versionstamps"][table] = int(stamp)
        _save_state(self.state_path, self.state)

    def _images(self, table):
        return self.state["images"].setdefault(table, {})

    def _remember(self, change):
        if change.table not in self.image_cache_tables:
            return
        images = self._images(change.table)
        if change.kind == "delete":
            images.pop(change.id, None)
        else:
            images[change.id] = change.after

    # -- one pass --

    def run_once(self):
        counts = {"entries": 0, "changes": 0, "handled": 0, "unhandled": 0, "errors": [], "per_table": {}}
        for table in self.tables:
            since = self.versionstamp(table)
            if since is None:
                since = 0 if self.replay_from_start else self.feed_end(table)
                self._set_versionstamp(table, since)
            per = counts["per_table"][table] = {"entries": 0, "changes": 0, "handled": 0, "from": since, "to": since}
            stopped = False
            while not stopped:
                page = self.show(table, since + 1, self.batch)
                if not page:
                    break
                for entry in page:
                    stamp = int(entry["versionstamp"])
                    changes = parse_entry(table, entry, self._images(table) if table in self.image_cache_tables else None)
                    if self._advance_before_dispatch:      # the deliberate break (see __init__)
                        self._set_versionstamp(table, stamp)
                    try:
                        for change in changes:
                            per["changes"] += 1
                            handlers = self.handlers.get((table, change.kind), [])
                            if not handlers:
                                counts["unhandled"] += 1
                            for handler in handlers:
                                handler(change, self.db)
                                per["handled"] += 1
                    except Exception as exc:  # any handler failure holds the versionstamp
                        counts["errors"].append({"table": table, "versionstamp": stamp,
                                                 "error": "%s: %s" % (type(exc).__name__, exc)})
                        stopped = True
                        break
                    for change in changes:
                        self._remember(change)
                    per["entries"] += 1
                    since = stamp
                    per["to"] = stamp
                    self._set_versionstamp(table, stamp)
                if len(page) < self.batch:
                    break
            counts["entries"] += per["entries"]
            counts["changes"] += per["changes"]
            counts["handled"] += per["handled"]
        return counts


def run_once(worker):
    return worker.run_once()


def run_forever(worker, interval_s=5.0, max_passes=None, log=print):
    """Poll the feeds every interval_s seconds until interrupted (or max_passes, for tests)."""
    passes = 0
    while max_passes is None or passes < max_passes:
        counts = worker.run_once()
        passes += 1
        if counts["entries"] or counts["errors"]:
            log(report_line(counts))
        if max_passes is not None and passes >= max_passes:
            break
        try:
            time.sleep(interval_s)
        except KeyboardInterrupt:
            break
    return passes


def report_line(counts):
    line = "QUEUE: %d entries, %d changes, %d handler calls, %d unhandled, %d errors" % (
        counts["entries"], counts["changes"], counts["handled"], counts["unhandled"], len(counts["errors"]))
    for err in counts["errors"]:
        line += "\n  ERROR %s @%d: %s" % (err["table"], err["versionstamp"], err["error"][:300])
    return line


# ---- shipped handlers ----------------------------------------------------------------------------

def _lit(values):
    return "[" + ", ".join("'%s'" % str(v).replace("'", "\\'") for v in values) + "]"


def _str(value):
    return json.dumps(str(value), ensure_ascii=False)


def _rec(record_id):
    return "type::record(%s)" % _str(record_id)


def _obj(value):
    """A Python value as a SurrealQL object literal (JSON is accepted; null becomes NULL)."""
    return "NONE" if value is None else json.dumps(value, ensure_ascii=False)


def stale_recheck_handlers(inst):
    """Facts confirmed on a citation that no longer confirms them go `stale`, with a review row.

    Fires on a unit whose grade or status changed (not on loader churn that rewrote the same values)
    and on a deleted cites edge. Idempotent: it re-reads the fact's current citations, changes only
    facts that are still `confirmed`, and writes reviews under a deterministic id.
    """
    lacking = ("count(SELECT VALUE id FROM $this->cites->unit WHERE grade IN %s AND status IN %s) = 0"
               % (_lit(inst.confirming_grades()), _lit(inst.usable_statuses())))

    def demote(facts, cause, kind, stamp, db):
        for fact in facts:
            db.sql("UPSERT review:[%s, %s, %d] SET target = %s, cause = %s, kind = %s, at = time::now();"
                   % (_str(fact), _str(cause), stamp, _rec(fact), _rec(cause), _str(kind)))
            db.sql("UPDATE %s SET status = 'stale' WHERE status = 'confirmed';" % _rec(fact))

    def on_unit_update(change, db):
        if not change.changed("grade", "status"):
            return  # loader churn or an unrelated field: nothing to re-check
        facts = db.sql("SELECT VALUE id FROM fact WHERE status = 'confirmed' AND id IN "
                       "(SELECT VALUE in FROM cites WHERE out = %s) AND %s;" % (_rec(change.id), lacking), expect=1)[0]
        demote([str(f) for f in facts], change.id, "stale_citation_unit_changed", change.versionstamp, db)

    def on_cites_delete(change, db):
        if change.before and change.before.get("in"):
            scope = "id = %s AND " % _rec(change.before["in"])
        else:
            scope = ""  # edge ends unknown (no cached image): sweep every confirmed fact
        facts = db.sql("SELECT VALUE id FROM fact WHERE %sstatus = 'confirmed' AND %s;" % (scope, lacking), expect=1)[0]
        demote([str(f) for f in facts], change.id, "stale_citation_deleted", change.versionstamp, db)

    return {("unit", "update"): on_unit_update, ("cites", "delete"): on_cites_delete}


def archive_handlers(tables=("fact", "conclusion", "critique")):
    """Every deleted claim row becomes an `archive` row with its last known image."""

    def on_delete(change, db):
        snapshot = change.before
        reason = (snapshot or {}).get("delete_reason") or "deleted"
        if snapshot is None:
            reason += " (%s)" % change.before_error
        db.sql("UPSERT archive:[%s, %s, %d] SET original_id = %s, original_table = %s, snapshot = %s, "
               "reason = %s, archived_at = time::now(), expires_at = NONE, legal_hold = false;"
               % (_str(change.table), _str(change.id), change.versionstamp, _rec(change.id), _str(change.table),
                  _obj(snapshot), _str(reason)))

    return {(table, "delete"): on_delete for table in tables}


def default_handlers(inst):
    handlers = {}
    for key, fn in list(stale_recheck_handlers(inst).items()) + list(archive_handlers().items()):
        handlers.setdefault(key, []).append(fn)
    return handlers


# ---- command line --------------------------------------------------------------------------------

def main(argv=None):
    parser = argparse.ArgumentParser(description="Change-feed work queue: stale re-checks and archiving.")
    parser.add_argument("instance")
    parser.add_argument("--url", default="http://127.0.0.1:8002/sql")
    parser.add_argument("--ns")
    parser.add_argument("--db")
    parser.add_argument("--state", required=True, help="JSON file holding the per-table versionstamps")
    parser.add_argument("--once", action="store_true", help="one pass, then exit")
    parser.add_argument("--interval", type=float, default=5.0)
    parser.add_argument("--apply", action="store_true", help="apply the changefeed surql first (ALTER TABLE only)")
    parser.add_argument("--retention", default="7d")
    parser.add_argument("--replay-from-start", action="store_true")
    parser.add_argument("--emit", action="store_true", help="print the changefeed surql and exit")
    args = parser.parse_args(argv)
    inst = config.load(args.instance)
    if args.emit:
        print(changefeed_surql(inst, args.retention)); return 0
    from xscholar import db as dbmod
    conn = dbmod.Db(url=args.url, ns=args.ns or inst.id, db=args.db or inst.id)
    conn.ping()
    if args.apply:
        conn.script(changefeed_surql(inst, args.retention))
    worker = Worker(conn, args.state, default_handlers(inst), replay_from_start=args.replay_from_start)
    if args.once:
        counts = worker.run_once()
        print(report_line(counts))
        return 1 if counts["errors"] else 0
    run_forever(worker, args.interval)
    return 0


if __name__ == "__main__":
    sys.exit(main())
