# -*- coding: utf-8 -*-
"""queue.py -- a durable, resumable work queue on SurrealDB change feeds (roadmap B11 / V2-4).

Re-checks and archiving happen without polling the tables and without losing anything across a
worker stop: the datastore keeps the change log, the worker keeps only a versionstamp per table.

    changefeed_surql(inst)          ALTER TABLE ... CHANGEFEED per claim table; review + archive tables
    Worker(db, state_path, handlers)
    run_once(worker)  -> counts     one pass over every table's new changes
    run_forever(worker, interval_s)

    python -m xscholar.queue INSTANCE.yaml --url URL --ns NS --db DB --state PATH [--once] [--apply]

Delivery contract (read this before writing a handler)
  * AT-LEAST-ONCE. The versionstamp for a table advances ONLY after every handler for every change
    in a feed entry returned without raising, and it is written to `state_path` before the next entry
    is read. A crash between a handler's side effect and that write re-delivers the entry. Handlers
    must therefore be IDEMPOTENT: the two shipped ones write with deterministic record ids
    (`review:[target, cause, versionstamp]`, `archive:[table, id, versionstamp]`) and re-check the
    current row before acting, so a second delivery is a no-op.
  * IN ORDER PER TABLE. A handler that raises stops that table at the failing entry; later entries
    for that table wait, other tables proceed. The error is counted and named in the run report.
  * FIRST RUN. With no state the worker starts from the current end of each feed (nothing replayed)
    unless `replay_from_start=True`.

What SurrealDB 3.1.6 puts in the feed (measured 2026-09-15, `research/DATABASE_FEATURES_2026-09-15.md`)
  * `SHOW CHANGES FOR TABLE t SINCE <int> LIMIT n` returns entries `{versionstamp, changes: [...]}`;
    SINCE is inclusive, so the worker asks for `last + 1`.
  * create  -> `{"update": {<full row>}}`
    update  -> `{"current": {<row after>}, "update": [<reverse JSON patch back to the row before>]}`
    delete  -> `{"delete": {"id": ...}}`   (no before-image on 3.1.x; delete images arrive in 3.2)
    schema  -> `{"define_table": {...}}`   (skipped)
  * `UPSERT/UPDATE ... CONTENT` with identical content still produces an entry with `update: []`
    (loader churn); `UPDATE ... SET` and `MERGE` with equal values produce none. The stale handler
    ignores any update whose patch touches neither `grade` nor `status`.
  * Because deletes carry no image, the worker keeps the last image it saw of every row in the
    tables named by `image_cache_tables` (in the state file) so the archive and stale handlers can
    still see what was deleted. A row created before the worker first ran has no cached image; the
    archive row then records that the snapshot is missing rather than pretending.

Standard library only.
"""
